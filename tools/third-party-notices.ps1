# Regenerates THIRD_PARTY_NOTICES.md from the modules linked into the
# Windows executable. Run after changing go.mod:
#   powershell -ExecutionPolicy Bypass -File tools\third-party-notices.ps1
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
Push-Location $root
try {
    $env:GOOS = 'windows'
    $modules = go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}}|{{.Version}}|{{.Dir}}{{end}}{{end}}' ./cmd/instantcapture |
        Where-Object { $_ } | Sort-Object -Unique

    $out = [System.Collections.Generic.List[string]]::new()
    $out.Add('# Third-party notices')
    $out.Add('')
    $out.Add('InstantCapture binaries include the following third-party software. Generated by `tools/third-party-notices.ps1`.')
    $out.Add('')
    $out.Add('Portions of this software are copyright (c) 2006-2017 The FreeType Project (www.freetype.org). All rights reserved. (`github.com/golang/freetype` is used under the FreeType License.)')

    $add = {
        param($title, $file)
        $out.Add('')
        $out.Add("## $title")
        $out.Add('')
        $out.Add('```text')
        foreach ($line in Get-Content -LiteralPath $file) { $out.Add($line.TrimEnd()) }
        $out.Add('```')
    }

    & $add "Go (standard library and runtime) $(go env GOVERSION)" (Join-Path (go env GOROOT) 'LICENSE')
    foreach ($entry in $modules) {
        $path, $version, $dir = $entry -split '\|', 3
        $license = Get-ChildItem -LiteralPath $dir -File |
            Where-Object { $_.Name -match '^(LICEN[CS]E|COPYING|UNLICENSE)' } | Select-Object -First 1
        if (-not $license) { throw "No license file found for $path" }
        & $add "$path $version" $license.FullName
        if ($path -eq 'github.com/golang/freetype') {
            & $add 'The FreeType License (selected for github.com/golang/freetype)' (Join-Path $dir 'licenses\ftl.txt')
        }
        if ($path -eq 'golang.org/x/image') {
            & $add 'Go fonts (golang.org/x/image/font/gofont)' (Join-Path $dir 'font\gofont\ttfs\README')
        }
    }
    Set-Content -LiteralPath (Join-Path $root 'THIRD_PARTY_NOTICES.md') -Value $out -Encoding utf8
} finally {
    Pop-Location
}
